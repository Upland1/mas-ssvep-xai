"""P24 documentation checks: Sources sections, cited paths exist, SVG parses, privacy, PF-31 naming.

Data-free: the `reports/` checks skip when that folder is absent.
The tree checked is the repository, or the one named by `P24_DOCS_ROOT` (e.g. a
clean clone after `make all`).
"""
import glob
import os
import re
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

ROOT = Path(os.environ.get("P24_DOCS_ROOT") or Path(__file__).resolve().parents[1]).resolve()
MD_DOCS = ["README.md", "RESEARCH_LOG.md", "docs/report/v2/report.md",
           "docs/progress_report/progress_report.md"]
SVG = "docs/infographic/methodology_infographic.svg"
ALL_DOCS = MD_DOCS + [SVG]

# characters that may appear inside a cited path
_PATH = r"[A-Za-z0-9_.*/\-<>{}\[\]]+"
REPORTS_RE = re.compile(r"(?<![A-Za-z0-9_./\-])reports/" + _PATH)
MAS_RE = re.compile(r"(?<![A-Za-z0-9_./\-])(?:mas|docs)/" + _PATH)
PHASE_REPORT_RE = re.compile(r"mas/state/reports/(P\d\d)\.md")


def _text(rel):
  return (ROOT / rel).read_text(encoding="utf-8")


def _clean(p):
  """Strip trailing punctuation and markdown/XML residue from a captured path."""
  p = p.rstrip(".,;:)]}>")
  return p


def _is_placeholder(p):
  return (bool(re.search(r"[<>{}\[\]]", p)) or "..." in p
          or bool(re.search(r"/Pxx|Pxx\.", p)))


def _cited(regex, rel):
  out = set()
  for m in regex.findall(_text(rel)):
    m = _clean(m)
    if m and not _is_placeholder(m):
      out.add(m)
  return sorted(out)


def _exists(rel_path, root=None):
  root = ROOT if root is None else Path(root)
  # git-ignored run-time locations (created by `make`) are not checked
  if rel_path.startswith("mas/state/scratch/"):
    return True
  # blocker ids are cited by their prefix (B003 for B003-cohort-beyond-S05.md)
  if re.fullmatch(r"mas/state/blockers/B\d{3}", rel_path):
    rel_path += "*"
  if any(c in rel_path for c in "*?"):
    return bool(glob.glob(str(root / rel_path)))
  return (root / rel_path).exists()


# --- make-all clone (02_plan.md, Verification V-2 and V-6) -------------------
# A tree regenerated by `make all` from a clean clone has no `reports/logs/`
# (logs are run artefacts, never committed) and has `reports/legacy_leaky/`.
# Only in such a tree are the two classes below accepted; in the main tree
# every cited `reports/` path must exist as written.
#
# V-6: outputs `make all` does not produce.
#   reports/loso_w1, loso_w1_all, loso_w1_fbcca_all, window_sweep_w1_all
#     (`make loso-all`, optional, outside `all`);
#   reports/logs (run logs; V-6 "logs");
#   reports/diagnostics (standalone diagnostic scripts outside the Makefile,
#     e.g. scripts/diagnostics/network_seed_spread.py, P11).
NOT_PRODUCED_BY_ALL = ("reports/loso_w1", "reports/loso_w1_all", "reports/loso_w1_fbcca_all",
                       "reports/window_sweep_w1_all", "reports/logs", "reports/diagnostics")
# V-2: Era-A files at `reports/<f>` in the main tree that `make all` writes to
# `reports/legacy_leaky/<f>`. Accepted only if the mapped file exists.
V2_ERA_A = re.compile(r"reports/(flagship_S\d+\.csv|eegnet_benchmark_cpu\.csv|eegnet_benchmark_cuda\.csv"
                      r"|compact_cnn_benchmark_cpu\.csv|shallow_convnet_benchmark_cpu\.csv"
                      r"|classification_report_[^/]*\.txt"
                      r"|feature_selection_sfs_(?:audit|diagnostics)_S03\.csv)")


def _is_make_all_clone(root):
  r = Path(root) / "reports"
  return r.is_dir() and not (r / "logs").exists() and (r / "legacy_leaky").is_dir()


def _reports_path_ok(rel_path, root=None):
  """True if the cited `reports/` path exists, or (make-all clone only) is V-2 mapped or V-6."""
  root = ROOT if root is None else Path(root)
  if _exists(rel_path, root):
    return True
  if not _is_make_all_clone(root):
    return False
  if any(rel_path == p or rel_path.startswith(p + "/") for p in NOT_PRODUCED_BY_ALL):
    return True
  m = V2_ERA_A.fullmatch(rel_path)
  return bool(m) and _exists("reports/legacy_leaky/" + m.group(1), root)


@pytest.mark.parametrize("rel", ALL_DOCS)
def test_document_exists(rel):
  assert (ROOT / rel).is_file(), rel


@pytest.mark.parametrize("rel", MD_DOCS)
def test_markdown_has_sources_section(rel):
  lines = _text(rel).splitlines()
  heads = [i for i, l in enumerate(lines) if re.match(r"^## Sources\s*$", l)]
  assert len(heads) == 1, f"{rel}: expected one '## Sources' heading, found {len(heads)}"
  body = [l for l in lines[heads[0] + 1:] if l.strip()]
  assert len(body) >= 3, f"{rel}: Sources section is empty"


def test_svg_parses_and_has_sources_note():
  root = ET.fromstring(_text(SVG))
  assert root.tag == "{http://www.w3.org/2000/svg}svg"
  texts = " ".join("".join(e.itertext()) for e in root.iter() if e.tag.endswith("text"))
  assert "Sources" in texts


@pytest.mark.parametrize("rel", ALL_DOCS)
def test_cited_reports_paths_exist(rel):
  if not (ROOT / "reports").is_dir():
    pytest.skip("reports/ absent (data-free CI)")
  missing = []
  for p in _cited(REPORTS_RE, rel):
    if p.startswith("reports/") and not _reports_path_ok(p.rstrip("/")):
      missing.append(p)
  assert not missing, f"{rel} cites missing paths: {missing}"


def _touch(root, rel):
  f = root / rel
  f.parent.mkdir(parents=True, exist_ok=True)
  f.write_text("x")


def test_reports_path_rule_synthetic(tmp_path):
  """Known answers for the V-2/V-6 acceptance rule on two synthetic trees."""
  main, clone = tmp_path / "main", tmp_path / "clone"
  for t in (main, clone):
    _touch(t, "reports/present.csv")
    _touch(t, "reports/legacy_leaky/flagship_S01.csv")
  _touch(main, "reports/logs/P11/run.log")
  assert not _is_make_all_clone(main) and _is_make_all_clone(clone)
  for t in (main, clone):
    assert _reports_path_ok("reports/present.csv", t)
    # an ordinary missing path fails in both trees
    assert not _reports_path_ok("reports/missing.csv", t)
    assert not _reports_path_ok("reports/loso_w1_s01/summary.csv", t)  # not a V-6 prefix
    # V-2 file whose legacy_leaky copy is also missing fails in both trees
    assert not _reports_path_ok("reports/flagship_S05.csv", t)
  # V-6 and V-2-mapped paths: rejected in the main tree, accepted in the clone
  for p in ("reports/loso_w1/summary.csv", "reports/loso_w1_all/summary.csv",
            "reports/window_sweep_w1_all", "reports/logs/P16", "reports/diagnostics/x.csv",
            "reports/flagship_S01.csv"):
    assert not _reports_path_ok(p, main), p
    assert _reports_path_ok(p, clone), p
  # a tree without legacy_leaky/ is not a make-all clone
  bare = tmp_path / "bare"
  _touch(bare, "reports/present.csv")
  assert not _reports_path_ok("reports/loso_w1/summary.csv", bare)


@pytest.mark.parametrize("rel", ALL_DOCS)
def test_cited_mas_and_docs_paths_exist(rel):
  missing = [p for p in _cited(MAS_RE, rel) if not _exists(p.rstrip("/"))]
  assert not missing, f"{rel} cites missing paths: {missing}"


@pytest.mark.parametrize("rel", ALL_DOCS)
def test_no_nonexistent_phase_report_cited(rel):
  missing = [f"mas/state/reports/{p}.md" for p in sorted(set(PHASE_REPORT_RE.findall(_text(rel))))
             if not (ROOT / f"mas/state/reports/{p}.md").is_file()]
  assert not missing, f"{rel}: {missing}"


@pytest.mark.parametrize("rel", MD_DOCS)
def test_no_bare_compact_model_name_in_tables(rel):
  """PF-31: table rows must say compact_cnn or compact_eegnet, not a bare 'compact'."""
  bad = []
  for i, line in enumerate(_text(rel).splitlines(), 1):
    if not line.lstrip().startswith("|"):
      continue
    for cell in (c.strip().strip("*`_ ") for c in line.strip().strip("|").split("|")):
      if cell.lower() in ("compact", "compact net", "compactnet"):
        bad.append((i, cell))
  assert not bad, f"{rel}: bare 'compact' model name in table cells {bad}"


# the guard's vendor/tool pattern, assembled from fragments so no term appears whole here
_TERMS = [["cla", "ude"], ["anthr", "opic"], ["co-", "auth", "ored-by"]]
_VENDOR = re.compile("|".join("".join(t) for t in _TERMS), re.I)


@pytest.mark.parametrize("rel", ALL_DOCS)
def test_privacy_no_vendor_terms(rel):
  hits = [(i, l.strip()[:60]) for i, l in enumerate(_text(rel).splitlines(), 1) if _VENDOR.search(l)]
  assert not hits, f"{rel}: vendor/tool term at lines {[h[0] for h in hits]}"
